function interpolate(raw: string, params?: Record<string, string | number>): string {
  if (!params) return raw;
  return Object.entries(params).reduce(
    (value, [key, replacement]) => value.replaceAll(`{${key}}`, String(replacement)),
    raw,
  );
}

export function translateClassDistributionMessage(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string | undefined {
  const raw = CLASS_DISTRIBUTION_MESSAGES[locale][key];
  return raw == null ? undefined : interpolate(raw, params);
}
