const MESSAGES: Record<Locale, AdminRequestMessages> = {
  ar: AR,
  en: EN,
  fr: FR,
  es: ES,
};

export function adminRequestMessage(
  locale: Locale,
  key: AdminRequestMessageKey,
  params?: Record<string, string | number>,
): string {
  const raw = MESSAGES[locale][key];
  if (!params) return raw;
  return Object.entries(params).reduce(
    (value, [param, replacement]) => value.replaceAll(`{${param}}`, String(replacement)),
    raw,
  );
}

export function adminRequestMessageKeys(): AdminRequestMessageKey[] {
  return Object.keys(EN) as AdminRequestMessageKey[];
}
